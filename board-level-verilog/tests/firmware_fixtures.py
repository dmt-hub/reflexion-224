"""Small programs authored here; no factory firmware is redistributed."""

def fixtures():
    # Four writes through the CPU front door, followed by actual WCS reads.
    # This row selects XREG and OUTA; byte order exercises lane decoding.
    audio = []
    saved = [0x7f, 0xd7, 0xfe, 0x03]
    for lane in [3, 1, 0, 2]:
        audio += [0x3e, saved[lane], 0x32, 0xfc + lane, 0x41]  # MVI A; STA
    audio += [0x3e,0x34,0xd3,6, 0x3e,0x12,0xd3,7]  # XREG low/high
    audio += [0x3a,0xfc,0x41, 0x32,0,0x20]  # LDA WCS; STA NVS
    audio += [0x3e,0,0xd3,1,0xd3,3,0x76]  # continuous; run; HLT
    yield 'wcs_audio', audio

    panel = [0x3e,0xc0,0xd3,0xe7, 0x3e,0xff,0xd3,0xe5,
             0x3e,0x6d,0xd3,0xe4, 0x3e,1,0xd3,0xe7, 0x3e,3,0xd3,0xe7]
    panel += [0] * 80  # ADC conversion time.
    panel += [0xdb,0xe4,0x32,0,0x20, 0x3e,0xf9,0xd3,0xe5,
              0xdb,0xe4,0x32,1,0x20, 0x3e,0xf8,0xd3,0xe5,
              0xdb,0xe4,0x32,2,0x20,0x76]
    yield 'panel_scan', panel

    yield 'serial_greeting', [0x3e,0x4e,0xd3,0xef, 0x3e,5,0xd3,0xef,
                              0x3e,0xe0,0xd3,0xee,0x76]
    for halted in [True, False]:
        irq = [0x31,0xf0,0x3f, 0x3e,0x4e,0xd3,0xef,
               0x3e,4,0xd3,0xef, 0xfb,0]  # SP; receive only; EI; NOP
        irq += [0x76] if halted else [0,0,0xc3,0x0d,0]
        irq += [0] * (0x38-len(irq))
        irq += [0xdb,0xee, 0x32,0,0x3c, 0x76 if halted else 0xc9]
        yield 'serial_irq_' + ('halted' if halted else 'running'), irq
